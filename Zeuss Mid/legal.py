DOCS = {"terms": TERMS, "privacy": PRIVACY}


def _split_block(text: str, limit: int) -> list[str]:
    """Режет слишком длинный блок по строкам, а потом по словам."""
    if len(text) <= limit:
        return [text]
    parts, cur = [], ""
    for line in text.split("\n"):
        while len(line) > limit:
            cut = line.rfind(" ", 0, limit)
            cut = cut if cut > 0 else limit
            if cur:
                parts.append(cur)
                cur = ""
            parts.append(line[:cut])
            line = line[cut:].lstrip()
        candidate = f"{cur}\n{line}" if cur else line
        if len(candidate) > limit:
            parts.append(cur)
            cur = line
        else:
            cur = candidate
    if cur:
        parts.append(cur)
    return parts


def doc_chunks(key: str) -> list[str]:
    """Документ в виде списка HTML-сообщений для Telegram (каждое короче лимита)."""
    doc = DOCS[key]
    esc = lambda s: html.escape(s, quote=False)
    blocks = [f"<b>{esc(doc['title'])}</b>\nZaetheron Industry\nРедакция от {DOC_DATE}"]
    for title, body in doc["sections"]:
        for i, piece in enumerate(_split_block(esc(body), TG_LIMIT - 300)):
            head = f"<b>{esc(title)}</b>\n" if i == 0 else ""
            blocks.append(head + piece)

    chunks, cur = [], ""
    for block in blocks:
        candidate = f"{cur}\n\n{block}" if cur else block
        if len(candidate) > TG_LIMIT and cur:
            chunks.append(cur)
            cur = block
        else:
            cur = candidate
    if cur:
        chunks.append(cur)
    return chunks


def as_json_for_web() -> dict:
    """Те же тексты для вставки в index.html."""
    out = {"version": DOC_VERSION, "date": DOC_DATE}
    for key, doc in DOCS.items():
        out[key] = {"title": doc["title"], "sections": [[t, b] for t, b in doc["sections"]]}
    return out


